/**
 * Print sha384 integrity hashes for the files people load from a CDN.
 * The hash changes every time those files change. Regenerate it before
 * each release and paste the new tags into README.md. See RELEASING.md.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
const version = pkg.version;
const files = [
  'dist/daily-kural.min.js',
  'dist/daily-kural.bundled.min.js',
  'fonts/fonts.css',
];

const tags = files.map((file) => {
  const hash = createHash('sha384').update(readFileSync(file)).digest('base64');
  const integrity = `sha384-${hash}`;
  const path = file;
  const url = `https://cdn.jsdelivr.net/npm/${pkg.name}@${version}/${path}`;
  const isCss = file.endsWith('.css');
  const tag = isCss
    ? `<link rel="stylesheet" href="${url}" integrity="${integrity}" crossorigin="anonymous">`
    : `<script src="${url}" integrity="${integrity}" crossorigin="anonymous"></script>`;
  return { file, integrity, url, tag };
});

const body = [
  `<!-- generated by scripts/sri.mjs for ${pkg.name}@${version} -->`,
  ...tags.map((item) => item.tag),
  '',
].join('\n');

mkdirSync('docs', { recursive: true });
writeFileSync('docs/sri.html', `${body}\n`);
console.log(`SRI for ${pkg.name}@${version}`);
console.log('These hashes match the local build. They match the CDN only after this exact build is published.');
console.log('They change on every release. Regenerate them in the release checklist.');
console.log('');
for (const item of tags) {
  console.log(item.file);
  console.log(item.integrity);
  console.log(item.tag);
  console.log('');
}
